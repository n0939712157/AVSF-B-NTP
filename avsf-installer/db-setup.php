<p class="avsf-muted"><?php _e('กรอกข้อมูล MySQL จากแผงควบคุม Hosting ระบบจะทดสอบการเชื่อมต่อก่อนบันทึก และสร้างตารางเริ่มต้นให้อัตโนมัติในขั้นตอนถัดไป'); ?></p>
