<?php
if (!defined('AVSF_ROOT')) define('AVSF_ROOT', dirname(__DIR__));
/** First-run database configuration. Writes config.local.php after a successful DB connection. */
if (is_file(AVSF_ROOT . '/config.local.php')) {
    header('Location: setup.php', true, 302);
    exit;
}
if (session_status() === PHP_SESSION_NONE) {
    session_set_cookie_params(['httponly' => true, 'samesite' => 'Lax', 'secure' => !empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off']);
    session_start();
}
// This entry point runs before config.local.php exists, so it cannot load config.php/bootstrap.
// Load the i18n layer directly so UI strings are translatable.
if (!defined('AVSF_CORE_DIR')) define('AVSF_CORE_DIR', AVSF_ROOT . DIRECTORY_SEPARATOR . 'avsf-core');
require_once AVSF_CORE_DIR . DIRECTORY_SEPARATOR . 'i18n.php';
if (empty($_SESSION['avsf_db_setup_csrf'])) $_SESSION['avsf_db_setup_csrf'] = bin2hex(random_bytes(32));
function avsf_db_setup_escape($value) { return htmlspecialchars((string)$value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'); }
$error = '';
$values = ['host' => '', 'port' => '3306', 'name' => '', 'user' => ''];
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    foreach ($values as $key => $default) $values[$key] = trim((string)($_POST[$key] ?? $default));
    $password = (string)($_POST['password'] ?? '');
    $token = (string)($_POST['csrf_token'] ?? '');
    $port = filter_var($values['port'], FILTER_VALIDATE_INT, ['options' => ['min_range' => 1, 'max_range' => 65535]]);
    if (!hash_equals((string)$_SESSION['avsf_db_setup_csrf'], $token)) {
        $error = __('เซสชันหมดอายุ กรุณาโหลดหน้าใหม่แล้วลองอีกครั้ง');
    } elseif (!preg_match('/^[a-zA-Z0-9.-]{1,255}$/', $values['host']) ||
        !preg_match('/^[a-zA-Z0-9_$-]{1,64}$/', $values['name']) ||
        !preg_match('/^[a-zA-Z0-9_$.-]{1,64}$/', $values['user']) || $port === false) {
        $error = __('กรุณาตรวจสอบ Host, Port, Database และ Username ให้ถูกต้อง');
    } elseif (!extension_loaded('mysqli')) {
        $error = __('เซิร์ฟเวอร์ยังไม่ได้เปิดใช้งาน PHP extension: mysqli');
    } else {
        mysqli_report(MYSQLI_REPORT_OFF);
        $test = @mysqli_connect($values['host'], $values['user'], $password, $values['name'], (int)$port);
        if (!$test) {
            error_log('AVSF DB setup connection test failed: ' . mysqli_connect_error());
            $error = __('เชื่อมต่อไม่ได้ กรุณาตรวจสอบ Host, Port, ชื่อฐานข้อมูล, Username และ Password');
        } else {
            mysqli_set_charset($test, 'utf8mb4');
            mysqli_close($test);
            $installNonce = bin2hex(random_bytes(32));
            $config = ['host' => $values['host'], 'port' => (int)$port, 'name' => $values['name'], 'user' => $values['user'], 'password' => $password, 'install_nonce' => $installNonce];
            $configCode = "<?php\n// Generated by AVSF first-run setup. Keep this file private.\nreturn " . var_export($config, true) . ";\n";
            $target = AVSF_ROOT . '/config.local.php';
            $temporary = $target . '.' . bin2hex(random_bytes(6)) . '.tmp';
            if (@file_put_contents($temporary, $configCode, LOCK_EX) === false || !@rename($temporary, $target)) {
                @unlink($temporary);
                $error = __('ตรวจสอบฐานข้อมูลผ่าน แต่บันทึก config.local.php ไม่ได้ กรุณาให้สิทธิ์เขียนไฟล์แก่ PHP');
            } else {
                @chmod($target, 0600);
                unset($_SESSION['avsf_db_setup_csrf']);
                // Bind the first-Owner wizard to the same browser session that supplied DB credentials.
                $_SESSION['avsf_install_nonce'] = $installNonce;
                header('Location: setup.php', true, 303);
                exit;
            }
        }
    }
}
