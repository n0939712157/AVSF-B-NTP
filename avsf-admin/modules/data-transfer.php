function avsfTransferLimitText($value, $maxChars) {
    $value = is_scalar($value) ? (string)$value : '';
    $maxChars = max(0, (int)$maxChars);
    if (function_exists('mb_substr')) return mb_substr($value, 0, $maxChars, 'UTF-8');
    if (function_exists('iconv_substr')) {
        $limited = @iconv_substr($value, 0, $maxChars, 'UTF-8');
        if ($limited !== false) return $limited;
    }
    return substr($value, 0, $maxChars);
}
function avsfTransferTextLength($value) {
    $value = (string)$value;
    if (function_exists('mb_strlen')) return mb_strlen($value, 'UTF-8');
    if (function_exists('iconv_strlen')) {
        $length = @iconv_strlen($value, 'UTF-8');
        if ($length !== false) return $length;
    }
    return strlen($value);
}
function avsfTransferEsc($value) {
    return htmlspecialchars((string)$value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}
function avsfTransferJsonRows($sql, $connection) {
    $result = mysqli_query($connection, $sql);
    if (!$result) throw new RuntimeException('อ่านข้อมูลส่งออกไม่สำเร็จ');
    $rows = [];
    while ($row = mysqli_fetch_assoc($result)) $rows[] = $row;
    mysqli_free_result($result);
    return $rows;
}
function avsfTransferSafeGeneralSettingKey($key) {
    $key = (string)$key;
    if ($key === '' || preg_match('/password|passwd|secret|token|api[_-]?key|credential|email|phone|proxy|permission|role|user|admin|siteurl|site_url|domain|database|db_/i', $key)) return false;
    $exact = [
        'siteName','siteDesc','siteLogo','siteIcon','siteLanguage','siteTimezone',
        'dateFormat','timeFormat','postsPerPage','mediaQuality','logoText',
        'announcement','site_ad_label','site_ad_close_label','site_banner_accessibility',
        'site_banner_interval_seconds','site_home_featured_all_label',
        'site_home_featured_interval_seconds','site_home_featured_limit',
        'site_home_featured_title','site_home_latest_title','site_search_button',
        'site_search_placeholder','videoKnownPlayers','video_ad_slots','vdohideIframeDomain','vdohideSupportedDomains'
    ];
    if (in_array($key, $exact, true)) return true;
    return (bool)preg_match('/^(?:theme_[a-z0-9_]+|site_menu_[a-z0-9_]+|card_columns_[a-z0-9_]+|card_rows_[a-z0-9_]+)$/i', $key);
}
function avsfTransferNormalizeAssetReference($value) {
    $value = trim((string)$value);
    if ($value === '') return '';
    $parts = parse_url($value);
    $base = parse_url(avsfCanonicalBaseUrl());
    if (is_array($parts) && !empty($parts['host']) && is_array($base) && !empty($base['host']) &&
        strtolower((string)$parts['host']) === strtolower((string)$base['host']) &&
        strtolower((string)($parts['scheme'] ?? 'https')) === strtolower((string)($base['scheme'] ?? 'https'))) {
        $path = (string)($parts['path'] ?? '/');
        $basePath = rtrim((string)($base['path'] ?? ''), '/');
        if ($basePath !== '' && strpos($path, $basePath . '/') === 0) $path = substr($path, strlen($basePath));
        return ($path !== '' ? $path : '/') . (isset($parts['query']) ? '?' . $parts['query'] : '');
    }
    return $value;
}
function avsfTransferSeoPackage($connection) {
    // Export persisted settings only. Defaults generated by PHP templates are not
    // written into the destination database; diagnostics make that distinction clear.
    $generalSettings = [];
    $seoSettings = [];
    $result = mysqli_query($connection, 'SELECT skey,svalue FROM settings ORDER BY skey');
    if (!$result) throw new RuntimeException('อ่านค่าตั้งค่าเว็บไซต์ไม่สำเร็จ');
    while ($row = mysqli_fetch_assoc($result)) {
        $settingKey = (string)$row['skey'];
        $settingValue = (string)($row['svalue'] ?? '');
        if (preg_match('/^seo_[a-z0-9_]{1,45}$/i', $settingKey) && !preg_match('/password|passwd|secret|token|api[_-]?key|credential/i', $settingKey)) {
            if (in_array($settingKey, ['seo_social_image'], true)) $settingValue = avsfTransferNormalizeAssetReference($settingValue);
            $seoSettings[$settingKey] = $settingValue;
            continue;
        }
        if (avsfTransferSafeGeneralSettingKey($settingKey)) {
            if (in_array($settingKey, ['siteLogo','siteIcon'], true)) $settingValue = avsfTransferNormalizeAssetReference($settingValue);
            $generalSettings[$settingKey] = $settingValue;
        }
    }
    mysqli_free_result($result);

    $permalinks = [
        'permalinkStructure' => (string)setting('permalinkStructure', 'postname'),
        'categoryBase' => (string)setting('categoryBase', 'category'),
        'tagBase' => (string)setting('tagBase', 'tag'),
        'actorBase' => (string)setting('actorBase', 'actor'),
        'studioBase' => (string)setting('studioBase', 'studio'),
    ];

    // Export effective SEO crawl defaults as well as persisted SEO keys. Some AVSF
    // defaults are resolved in PHP and may not exist as rows in the settings table.
    $seoSavedCount = count($seoSettings);
    if (!isset($seoSettings['seo_robots'])) $seoSettings['seo_robots'] = (string)setting('seo_robots', 'index, follow');
    $indexTypes = [
        'home'=>'seo_index_home','all'=>'seo_index_all','category_list'=>'seo_index_category_list',
        'studio_list'=>'seo_index_studio_list','actor_list'=>'seo_index_actor_list','tag_list'=>'seo_index_tag_list',
        'post'=>'seo_index_posts','page'=>'seo_index_pages','category'=>'seo_index_categories',
        'studio'=>'seo_index_studios','actor'=>'seo_index_actors','tag'=>'seo_index_tags'
    ];
    foreach ($indexTypes as $type => $key) {
        if (!isset($seoSettings[$key])) $seoSettings[$key] = function_exists('seoIndexDefault') && seoIndexDefault($type) ? 'index' : 'noindex';
    }
    $sitemapTypes = ['posts'=>'seo_sitemap_max_posts','pages'=>'seo_sitemap_max_pages','categories'=>'seo_sitemap_max_categories','studios'=>'seo_sitemap_max_studios','actors'=>'seo_sitemap_max_actors','tags'=>'seo_sitemap_max_tags'];
    foreach ($sitemapTypes as $key => $settingKey) {
        if (!isset($seoSettings[$settingKey])) $seoSettings[$settingKey] = (string)setting($settingKey, '20000');
    }
    $seoCount = count($seoSettings);
    $generalCount = count($generalSettings);
    $notes = [];
    if ($seoSavedCount === 0) $notes[] = __('ไม่พบแถว seo_* ที่บันทึกไว้ใน settings; ส่งออกค่า Index/Robots/Sitemap ที่ระบบใช้จริงเพิ่มเติมเพื่อให้ย้ายค่าเริ่มต้นได้');
    if ($generalCount === 0) $notes[] = __('ไม่พบค่าตั้งค่าทั่วไปที่อนุญาตให้ส่งออก');

    return [
        'format' => 'avsf-Settings-Export',
        'version' => 2,
        'exported_at' => gmdate('c'),
        'product' => 'AVSF',
        'description' => 'Settings-only migration package. Contains safe general settings, global SEO settings and permalink rules. No posts, pages, taxonomy records, users or domain settings.',
        'general_settings' => $generalSettings,
        'seo_settings' => $seoSettings,
        'permalinks' => $permalinks,
        'diagnostics' => [
            'general_saved_keys' => $generalCount,
            'seo_saved_keys' => $seoSavedCount,
            'seo_exported_keys' => $seoCount,
            'permalink_values' => count($permalinks),
            'notes' => $notes,
        ],
    ];
}
function avsfXmlClean($value) {
    $value = (string)$value;
    if (!preg_match('//u', $value) && function_exists('iconv')) {
        $converted = @iconv('UTF-8', 'UTF-8//IGNORE', $value);
        if (is_string($converted)) $value = $converted;
    }
    $clean = preg_replace('/[\x00-\x08\x0B\x0C\x0E-\x1F]/', '', $value);
    return is_string($clean) ? $clean : '';
}
function avsfXmlCdata($value) {
    return '<![CDATA[' . str_replace(']]>', ']]]]><![CDATA[>', avsfXmlClean($value)) . ']]>';
}
function avsfXmlTag($name, $value) {
    return '<' . $name . '>' . avsfXmlCdata($value) . '</' . $name . '>';
}
function avsfXmlText($name, $value) {
    return '<' . $name . '>' . htmlspecialchars(avsfXmlClean($value), ENT_XML1 | ENT_COMPAT | ENT_SUBSTITUTE, 'UTF-8') . '</' . $name . '>';
}
function avsfTransferBaseUrl() {
    return rtrim(avsfCanonicalBaseUrl(), '/');
}
function avsfTransferAbsoluteUrl($value, $baseUrl) {
    $value = trim((string)$value);
    if ($value === '') return '';
    if (preg_match('~^https?://~i', $value)) return $value;
    if (strpos($value, '//') === 0) return 'https:' . $value;
    return rtrim($baseUrl, '/') . '/' . ltrim($value, '/');
}
function avsfTransferPostDate($post) {
    // AVSF public publication date is posts.date; createdAt is the original upload timestamp.
    $dateValue = trim((string)($post['date'] ?? ''));
    if ($dateValue === '' || strpos($dateValue, '0000-00-00') === 0) $dateValue = trim((string)($post['createdAt'] ?? ''));
    if ($dateValue === '' || strpos($dateValue, '0000-00-00') === 0) $dateValue = 'now';
    $timezone = (string)setting('siteTimezone', 'Asia/Bangkok');
    try {
        $date = new DateTimeImmutable($dateValue, new DateTimeZone($timezone));
    } catch (Throwable $error) {
        $date = new DateTimeImmutable('now', new DateTimeZone('UTC'));
    }
    return $date;
}
function avsfTransferImageMime($url) {
    $path = (string)(parse_url($url, PHP_URL_PATH) ?: '');
    $ext = strtolower(pathinfo($path, PATHINFO_EXTENSION));
    $types = ['jpg'=>'image/jpeg','jpeg'=>'image/jpeg','png'=>'image/png','webp'=>'image/webp','gif'=>'image/gif','avif'=>'image/avif'];
    return $types[$ext] ?? 'application/octet-stream';
}
function avsfTransferDecodeIds($raw) {
    $decoded = json_decode((string)$raw, true);
    if (!is_array($decoded)) return [];
    return array_values(array_filter(array_map('intval', $decoded), function($id) { return $id > 0; }));
}
function avsfTransferGalleryValues($value) {
    $decoded = json_decode((string)$value, true);
    if (!is_array($decoded)) {
        $raw = (string)$value;
        $found = [];
        if (preg_match_all("~(?:https?://[^\\s\"']+|/?(?:uploads|media)/[^\\s,;\"']+)\\.(?:jpg|jpeg|png|webp|gif|avif)(?:\\?[^\\s,;\"']*)?~i", $raw, $matches)) {
            foreach ($matches[0] as $candidate) $found[] = trim($candidate);
        }
        return array_values(array_unique($found));
    }
    $found = [];
    $walk = function($item) use (&$walk, &$found) {
        if (is_string($item)) {
            $candidate = trim($item);
            if ($candidate !== '' && preg_match('~(https?://|/|uploads/|media/).+\.(jpg|jpeg|png|webp|gif|avif)(\?.*)?$~i', $candidate)) $found[] = $candidate;
        } elseif (is_array($item)) {
            foreach ($item as $child) $walk($child);
        }
    };
    $walk($decoded);
    return array_values(array_unique($found));
}
function avsfTransferContentImages($content) {
    $html = (string)$content;
    $found = [];
    if (preg_match_all('/(?:src|data-src)\s*=\s*([\"\'])(.*?)\1/is', $html, $matches)) {
        foreach ($matches[2] as $candidate) {
            $candidate = trim(html_entity_decode((string)$candidate, ENT_QUOTES | ENT_HTML5, 'UTF-8'));
            if ($candidate === '' || stripos($candidate, 'data:') === 0) continue;
            $mime = avsfTransferImageMime($candidate);
            if (strpos($mime, 'image/') === 0) $found[] = $candidate;
        }
    }
    if (preg_match_all('/srcset\s*=\s*([\"\'])(.*?)\1/is', $html, $srcsetMatches)) {
        foreach ($srcsetMatches[2] as $srcset) {
            foreach (explode(',', (string)$srcset) as $candidate) {
                $parts = preg_split('/\s+/', trim($candidate));
                $url = trim((string)($parts[0] ?? ''));
                if ($url === '' || stripos($url, 'data:') === 0) continue;
                $mime = avsfTransferImageMime($url);
                if (strpos($mime, 'image/') === 0) $found[] = html_entity_decode($url, ENT_QUOTES | ENT_HTML5, 'UTF-8');
            }
        }
    }
    return array_values(array_unique($found));
}
function avsfTransferPostStatusCounts($connection) {
    $counts = [];
    $result = mysqli_query($connection, 'SELECT status, COUNT(*) AS total FROM posts GROUP BY status');
    if (!$result) throw new RuntimeException('อ่านจำนวนโพสต์ตามสถานะไม่สำเร็จ');
    while ($row = mysqli_fetch_assoc($result)) $counts[(string)$row['status']] = (int)$row['total'];
    mysqli_free_result($result);
    return $counts;
}
function avsfTransferWxr($connection, $selectedStatuses = null) {
    $allowedStatuses = ['publish','draft','pending','private','future','trash'];
    if (!is_array($selectedStatuses)) $selectedStatuses = $allowedStatuses;
    $selectedStatuses = array_values(array_unique(array_intersect($allowedStatuses, $selectedStatuses)));
    if (!$selectedStatuses) throw new RuntimeException('กรุณาเลือกสถานะโพสต์อย่างน้อยหนึ่งรายการ');
    $baseUrl = avsfTransferBaseUrl();
    $quotedStatuses = array_map(function($status) use ($connection) { return "'" . mysqli_real_escape_string($connection, $status) . "'"; }, $selectedStatuses);
    $postsResult = mysqli_query($connection, 'SELECT * FROM posts WHERE status IN (' . implode(',', $quotedStatuses) . ') ORDER BY id ASC');
    if (!$postsResult) throw new RuntimeException('อ่านโพสต์เพื่อสร้าง XML ไม่สำเร็จ');

    $studioNames = [];
    foreach (avsfTransferJsonRows("SELECT id,name FROM studios", $connection) as $row) $studioNames[(int)$row['id']] = (string)$row['name'];
    $actorNames = [];
    $actorSlugs = [];
    foreach (avsfTransferJsonRows("SELECT id,name,slug FROM actors", $connection) as $row) {
        $actorNames[(int)$row['id']] = (string)$row['name'];
        $actorSlugs[(function_exists('mb_strtolower') ? mb_strtolower((string)$row['name'], 'UTF-8') : strtolower((string)$row['name']))] = (string)$row['slug'];
    }
    $tagNames = [];
    $tagSlugs = [];
    foreach (avsfTransferJsonRows("SELECT id,name,slug FROM tags", $connection) as $row) {
        $tagNames[(int)$row['id']] = (string)$row['name'];
        $tagSlugs[(function_exists('mb_strtolower') ? mb_strtolower((string)$row['name'], 'UTF-8') : strtolower((string)$row['name']))] = (string)$row['slug'];
    }
    $categorySlugs = [];
    foreach (avsfTransferJsonRows("SELECT name,slug FROM categories", $connection) as $row) $categorySlugs[(function_exists('mb_strtolower') ? mb_strtolower((string)$row['name'], 'UTF-8') : strtolower((string)$row['name']))] = (string)$row['slug'];
    $studioSlugs = [];
    foreach (avsfTransferJsonRows("SELECT id,name,slug FROM studios", $connection) as $row) $studioSlugs[(int)$row['id']] = (string)$row['slug'];

    $taxonomies = [
        'category' => avsfTransferJsonRows("SELECT id,name,slug,metaDesc FROM categories ORDER BY id", $connection),
        'post_tag' => avsfTransferJsonRows("SELECT id,name,slug,'' AS metaDesc FROM tags ORDER BY id", $connection),
        'studio' => avsfTransferJsonRows("SELECT id,name,slug,`desc` AS metaDesc FROM studios ORDER BY id", $connection),
        'actor' => avsfTransferJsonRows("SELECT id,name,slug,bio AS metaDesc FROM actors ORDER BY id", $connection),
    ];
    $commentsByPost = [];
    foreach (avsfTransferJsonRows("SELECT id,postId,name,text,date,approved FROM comments ORDER BY id", $connection) as $commentRow) {
        $commentsByPost[(int)$commentRow['postId']][] = $commentRow;
    }

    $now = gmdate('D, d M Y H:i:s') . ' GMT';
    $siteName = (string)setting('siteName', 'AVSF');
    $siteDesc = (string)setting('siteDesc', '');
    $language = (string)setting('siteLanguage', 'th');

    header('Content-Type: application/xml; charset=UTF-8');
    header('Content-Disposition: attachment; filename="avsf-wordpress-wxr-' . gmdate('Ymd-His') . '.xml"');
    header('X-Content-Type-Options: nosniff');
    header('Cache-Control: no-store, private');
    echo "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n";
    echo '<rss version="2.0" xmlns:excerpt="http://wordpress.org/export/1.2/excerpt/" xmlns:content="http://purl.org/rss/1.0/modules/content/" xmlns:wfw="http://wellformedweb.org/CommentAPI/" xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:wp="http://wordpress.org/export/1.2/">' . "\n<channel>\n";
    echo avsfXmlTag('title', $siteName) . "\n";
    echo avsfXmlTag('link', $baseUrl . '/') . "\n";
    echo avsfXmlTag('description', $siteDesc) . "\n";
    echo avsfXmlTag('pubDate', $now) . "\n";
    echo avsfXmlTag('language', $language) . "\n";
    echo '<wp:wxr_version>1.2</wp:wxr_version>' . "\n";
    echo avsfXmlTag('wp:base_site_url', $baseUrl . '/') . "\n";
    echo avsfXmlTag('wp:base_blog_url', $baseUrl . '/') . "\n";
    echo '<wp:author><wp:author_id>1</wp:author_id>' . avsfXmlTag('wp:author_login', 'avsf') . avsfXmlTag('wp:author_email', '') . avsfXmlTag('wp:author_display_name', 'AVSF') . '<wp:author_first_name></wp:author_first_name><wp:author_last_name></wp:author_last_name></wp:author>' . "\n";

    // AVSF stores term IDs in separate tables; allocate WXR-wide IDs to avoid
    // collisions when category/tag/studio/actor source IDs happen to be equal.
    $wxrTermId = 0;
    foreach ($taxonomies['category'] as $term) {
        $wxrTermId++;
        echo '<wp:category><wp:term_id>' . $wxrTermId . '</wp:term_id>' . avsfXmlTag('wp:category_nicename', $term['slug']) . '<wp:category_parent></wp:category_parent>' . avsfXmlTag('wp:cat_name', $term['name']) . avsfXmlTag('wp:category_description', $term['metaDesc']) . '</wp:category>' . "\n";
    }
    foreach ($taxonomies['post_tag'] as $term) {
        $wxrTermId++;
        echo '<wp:tag><wp:term_id>' . $wxrTermId . '</wp:term_id>' . avsfXmlTag('wp:tag_slug', $term['slug']) . avsfXmlTag('wp:tag_name', $term['name']) . avsfXmlTag('wp:tag_description', $term['metaDesc']) . '</wp:tag>' . "\n";
    }
    foreach (['studio','actor'] as $taxType) {
        foreach ($taxonomies[$taxType] as $term) {
            $wxrTermId++;
            echo '<wp:term><wp:term_id>' . $wxrTermId . '</wp:term_id>' . avsfXmlTag('wp:term_taxonomy', $taxType) . avsfXmlTag('wp:term_slug', $term['slug']) . avsfXmlTag('wp:term_name', $term['name']) . avsfXmlTag('wp:term_parent', '') . avsfXmlTag('wp:term_description', $term['metaDesc']) . '</wp:term>' . "\n";
        }
    }

    $attachmentMap = [];
    $attachmentCounter = 0;
    while ($post = mysqli_fetch_assoc($postsResult)) {
        $postId = (int)$post['id'];
        $postDate = avsfTransferPostDate($post);
        $postDateLocal = $postDate->format('Y-m-d H:i:s');
        $postDateGmt = $postDate->setTimezone(new DateTimeZone('UTC'))->format('Y-m-d H:i:s');
        $postDateRss = $postDate->format(DATE_RSS);
        $status = in_array((string)$post['status'], ['publish','draft','pending','private','future','trash'], true) ? (string)$post['status'] : 'draft';
        $slug = (string)$post['slug'];
        $postLink = $baseUrl . sitePath('post', $slug, [], $post);

        $imageFields = [
            'cover' => avsfTransferAbsoluteUrl($post['cover'] ?? '', $baseUrl),
            'poster' => avsfTransferAbsoluteUrl($post['posterUrl'] ?? '', $baseUrl),
        ];
        $galleryImages = [];
        foreach (avsfTransferGalleryValues($post['gallery'] ?? '') as $galleryValue) $galleryImages[] = avsfTransferAbsoluteUrl($galleryValue, $baseUrl);
        foreach (avsfTransferContentImages($post['content'] ?? '') as $contentImage) $galleryImages[] = avsfTransferAbsoluteUrl($contentImage, $baseUrl);
        $mediaUrls = array_values(array_unique(array_filter(array_merge(array_values($imageFields), $galleryImages))));
        foreach ($mediaUrls as $mediaUrl) {
            if (!isset($attachmentMap[$mediaUrl])) {
                $attachmentCounter++;
                $attachmentMap[$mediaUrl] = [
                    'id' => 1000000000 + $attachmentCounter,
                    'url' => $mediaUrl,
                    'parent' => $postId,
                    'date' => $postDate,
                    'mime' => avsfTransferImageMime($mediaUrl),
                ];
            }
        }

        $categoryValues = function_exists('splitTaxonomyNames') ? splitTaxonomyNames((string)($post['category'] ?? '')) : array_filter(array_map('trim', explode(',', (string)($post['category'] ?? ''))));
        $actorIds = avsfTransferDecodeIds($post['actorIds'] ?? '');
        $tagIds = avsfTransferDecodeIds($post['tagIds'] ?? '');
        $actorValueNames = [];
        foreach ($actorIds as $actorId) if (isset($actorNames[$actorId])) $actorValueNames[] = $actorNames[$actorId];
        $tagValueNames = [];
        foreach ($tagIds as $tagId) if (isset($tagNames[$tagId])) $tagValueNames[] = $tagNames[$tagId];
        $studioId = (int)($post['studioId'] ?? 0);
        $studioName = $studioNames[$studioId] ?? '';

        echo "<item>\n";
        echo avsfXmlTag('title', $post['title'] ?? '') . "\n";
        echo avsfXmlTag('link', html_entity_decode($postLink, ENT_QUOTES, 'UTF-8')) . "\n";
        echo avsfXmlTag('pubDate', $postDateRss) . "\n";
        echo avsfXmlTag('dc:creator', $post['author'] ?? 'avsf') . "\n";
        echo '<guid isPermaLink="false">' . htmlspecialchars('urn:avsf:post:' . $postId, ENT_XML1 | ENT_COMPAT, 'UTF-8') . '</guid>' . "\n";
        echo '<description></description>' . "\n";
        echo avsfXmlTag('content:encoded', $post['content'] ?? '') . "\n";
        echo avsfXmlTag('excerpt:encoded', '') . "\n";
        echo '<wp:post_id>' . $postId . '</wp:post_id>' . "\n";
        echo avsfXmlTag('wp:post_date', $postDateLocal) . "\n";
        echo avsfXmlTag('wp:post_date_gmt', $postDateGmt) . "\n";
        echo '<wp:comment_status>closed</wp:comment_status><wp:ping_status>closed</wp:ping_status>' . "\n";
        echo avsfXmlTag('wp:post_name', $slug) . "\n";
        echo avsfXmlTag('wp:status', $status) . "\n";
        echo '<wp:post_parent>0</wp:post_parent><wp:menu_order>0</wp:menu_order>' . "\n";
        echo avsfXmlTag('wp:post_type', 'post') . "\n";
        echo '<wp:post_password></wp:post_password><wp:is_sticky>0</wp:is_sticky>' . "\n";

        foreach ($categoryValues as $categoryName) {
            $categoryName = trim((string)$categoryName);
