                if (in_array($key, ['siteLogo','siteIcon'], true) && $value !== '' && (!validImageReference($value) || strlen($value) > 2000)) { $counts['skipped']++; continue; }
                if ($key === 'siteName' && (trim($value) === '' || avsfTransferTextLength($value) > 200)) { $counts['skipped']++; continue; }
                if ($key === 'siteDesc' && avsfTransferTextLength($value) > 5000) { $counts['skipped']++; continue; }
