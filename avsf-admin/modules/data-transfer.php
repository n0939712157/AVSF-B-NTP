                if ($key === 'seo_robots' && !in_array($value, ['index, follow','index, nofollow','noindex, follow','noindex, nofollow'], true)) { $counts['skipped']++; continue; }
                if ($key === 'seo_social_twitter_card' && !in_array($value, ['summary','summary_large_image'], true)) { $counts['skipped']++; continue; }
