function avsfTransferNormalizeImportPackage($package) {
    if (!is_array($package)) throw new RuntimeException('ไฟล์ JSON ไม่ใช่ข้อมูลแบบ object');
    if (($package['format'] ?? '') === 'avsf-Settings-Export' && (int)($package['version'] ?? 0) === 2) {
        $general = $package['general_settings'] ?? [];
        $seo = $package['seo_settings'] ?? [];
        $permalinks = $package['permalinks'] ?? [];
        if (!is_array($general) || !is_array($seo) || !is_array($permalinks)) throw new RuntimeException('โครงสร้างไฟล์ Settings Export ไม่ถูกต้อง');
        return ['format'=>'v2','general_settings'=>$general,'seo_settings'=>$seo,'permalinks'=>$permalinks,'source_name'=>(string)($package['general_settings']['siteName'] ?? $package['product'] ?? 'AVSF')];
    }
    // Import PinkCMS/B-NTP SEO settings export used by the legacy source site.
    // Only global SEO settings and portable crawl defaults are migrated; per-record
    // metadata, taxonomy rows, redirects and ID-based overrides are intentionally ignored.
    if (($package['format'] ?? '') === 'bntp.pinkcms.seo-settings') {
        $payload = is_array($package['payload'] ?? null) ? $package['payload'] : [];
        $seo = is_array($payload['settings'] ?? null) ? $payload['settings'] : [];
        $seo = array_filter($seo, function($value, $key) {
            return is_string($key) && preg_match('/^seo_[a-z0-9_]{1,45}$/i', $key) && is_scalar($value);
        }, ARRAY_FILTER_USE_BOTH);
        $crawl = is_array($payload['crawl_controls'] ?? null) ? $payload['crawl_controls'] : [];
        $indexMap = [
            'home'=>'seo_index_home','all'=>'seo_index_all','category_list'=>'seo_index_category_list',
            'studio_list'=>'seo_index_studio_list','actor_list'=>'seo_index_actor_list','tag_list'=>'seo_index_tag_list',
            'post'=>'seo_index_posts','page'=>'seo_index_pages','category'=>'seo_index_categories',
            'studio'=>'seo_index_studios','actor'=>'seo_index_actors','tag'=>'seo_index_tags'
        ];
        foreach (($crawl['index_defaults'] ?? []) as $type => $value) {
            if (isset($indexMap[$type]) && in_array($value, ['index','noindex'], true) && !isset($seo[$indexMap[$type]])) $seo[$indexMap[$type]] = $value;
        }
        if (!isset($seo['seo_robots']) && in_array(($crawl['robots_default'] ?? ''), ['index, follow','index, nofollow','noindex, follow','noindex, nofollow'], true)) $seo['seo_robots'] = $crawl['robots_default'];
        $limitMap = ['post'=>'seo_sitemap_max_posts','page'=>'seo_sitemap_max_pages','category'=>'seo_sitemap_max_categories','studio'=>'seo_sitemap_max_studios','actor'=>'seo_sitemap_max_actors','tag'=>'seo_sitemap_max_tags'];
        foreach (($crawl['sitemap_limits'] ?? []) as $type => $value) {
            if (isset($limitMap[$type]) && (is_int($value) || (is_string($value) && ctype_digit($value))) && (int)$value <= 50000) $seo[$limitMap[$type]] = (string)(int)$value;
        }
        $templates = is_array($crawl['post_meta_templates'] ?? null) ? $crawl['post_meta_templates'] : [];
        if (isset($templates['meta_title']) && is_string($templates['meta_title'])) $seo['seo_post_meta_title_template'] = $templates['meta_title'];
        if (isset($templates['meta_description']) && is_string($templates['meta_description'])) $seo['seo_post_meta_desc_template'] = $templates['meta_description'];
        return [
            'format'=>'pinkcms-seo-v1', 'general_settings'=>[], 'seo_settings'=>$seo, 'permalinks'=>[],
            'source_name'=>(string)($package['source']['site_name'] ?? 'PinkCMS legacy SEO export'),
            'source_assets'=>is_array($package['assets'] ?? null) ? $package['assets'] : [],
            'import_notes'=>[__('นำเข้าเฉพาะ SEO Settings กลางและค่า Robots/Index/Sitemap; ไม่รวมข้อมูลโพสต์ รายการ Taxonomy, Meta รายเรื่อง, Index Override ราย ID และ Redirect')]
        ];
    }
    // Backward compatibility for AVSF SEO JSON v1 exports.
    if (($package['format'] ?? '') === 'avsf-SEO-Export' && (int)($package['version'] ?? 0) === 1) {
        $general = [];
        $identity = $package['site_identity'] ?? [];
        if (is_array($identity)) {
            if (isset($identity['siteName']) && is_string($identity['siteName'])) $general['siteName'] = $identity['siteName'];
            if (isset($identity['siteDesc']) && is_string($identity['siteDesc'])) $general['siteDesc'] = $identity['siteDesc'];
        }
        $seo = $package['settings'] ?? [];
        $permalinks = $package['permalinks'] ?? [];
        if (!is_array($seo) || !is_array($permalinks)) throw new RuntimeException('โครงสร้างไฟล์ SEO JSON v1 ไม่ถูกต้อง');
        return ['format'=>'legacy-v1','general_settings'=>$general,'seo_settings'=>$seo,'permalinks'=>$permalinks,'source_name'=>(string)($identity['siteName'] ?? 'AVSF (legacy export)')];
    }
    throw new RuntimeException('ไม่รองรับไฟล์นี้ ต้องเป็น AVSF Settings Export v2, AVSF SEO Export v1 หรือ PinkCMS SEO Settings Export');
}
