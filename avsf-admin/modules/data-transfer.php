            elseif (in_array($key, ['permalinkStructure','categoryBase','tagBase','actorBase','studioBase'], true)) $counts['permalinks']++;
            else $counts['general']++;
        }
        if (!mysqli_commit($conn)) throw new RuntimeException('ยืนยันการบันทึก Settings ไม่สำเร็จ');
        AVSFCache::clearAll(AVSF_CACHE_DIR);
        logActivity('นำเข้า General + SEO Settings จาก Settings Migration package');
        avsfTransferCleanupStagedSeoAssets($preview);
        unset($_SESSION['avsf_settings_transfer_preview'], $_SESSION['avsf_settings_transfer_preview_at']);
        avsfTransferSetNotice('success', __('นำเข้าการตั้งค่าเสร็จแล้ว · General %s · SEO %s · Permalink %s · ข้าม %s · Backup: %s', [$counts['general'], $counts['seo'], $counts['permalinks'], $counts['skipped'], $backupName]));
    } catch (Throwable $error) {
        if (isset($conn) && $conn instanceof mysqli) @mysqli_rollback($conn);
        foreach ($createdAssetFiles as $createdAssetFile) if (is_file($createdAssetFile)) @unlink($createdAssetFile);
        error_log('AVSF Settings migration failed: ' . $error->getMessage());
        avsfTransferSetNotice('error', 'นำเข้าไม่สำเร็จ: ' . $error->getMessage());
    }
    header('Location: data-transfer.php'); exit;
}

