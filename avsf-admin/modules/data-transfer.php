function avsfTransferStageSeoAssetsFromZip($zipPath, $normalized) {
    if (!is_array($normalized['source_assets'] ?? null) || !$normalized['source_assets']) return $normalized;
    if (!class_exists('ZipArchive')) throw new RuntimeException('เซิร์ฟเวอร์ไม่มี ZipArchive สำหรับอ่านไฟล์แพ็กเกจ SEO');
    $zip = new ZipArchive();
    if ($zip->open($zipPath, ZipArchive::CHECKCONS) !== true) throw new RuntimeException('ไฟล์ ZIP SEO เสียหายหรือเปิดไม่ได้');
    $token = bin2hex(random_bytes(12));
    $stageDir = avsfTransferAssetStageRoot() . DIRECTORY_SEPARATOR . $token;
    if (!@mkdir($stageDir, 0700, true)) { $zip->close(); throw new RuntimeException('สร้างโฟลเดอร์พักไฟล์ภาพไม่สำเร็จ'); }
    $staged = [];
    $totalBytes = 0;
    try {
        foreach ($normalized['source_assets'] as $asset) {
            if (!is_array($asset) || empty($asset['package_path']) || empty($asset['setting_key'])) continue;
            $entry = (string)$asset['package_path'];
            if (!preg_match('~^assets/[A-Za-z0-9._-]+\.(?:jpe?g|png|gif|webp|avif)$~i', $entry)) continue;
            $stat = $zip->statName($entry);
            if (!$stat) continue;
            $size = (int)($stat['size'] ?? 0);
            if ($size < 1 || $size > 5 * 1024 * 1024) throw new RuntimeException('ไฟล์ภาพ SEO ต้องมีขนาดไม่เกิน 5 MB');
            $totalBytes += $size;
            if ($totalBytes > 20 * 1024 * 1024) throw new RuntimeException('ไฟล์ภาพรวมในแพ็กเกจ SEO เกิน 20 MB');
            $bytes = $zip->getFromName($entry);
            if (!is_string($bytes) || strlen($bytes) !== $size) throw new RuntimeException('อ่านไฟล์ภาพจาก ZIP ไม่ครบ');
            $tmp = $stageDir . DIRECTORY_SEPARATOR . bin2hex(random_bytes(12)) . '.img';
            if (file_put_contents($tmp, $bytes, LOCK_EX) !== strlen($bytes)) throw new RuntimeException('บันทึกไฟล์ภาพพักชั่วคราวไม่สำเร็จ');
            @chmod($tmp, 0600);
            $finfo = finfo_open(FILEINFO_MIME_TYPE);
            $mime = $finfo ? finfo_file($finfo, $tmp) : '';
            if ($finfo) finfo_close($finfo);
            $image = @getimagesize($tmp);
            $allowed = ['image/jpeg'=>'jpg','image/png'=>'png','image/gif'=>'gif','image/webp'=>'webp','image/avif'=>'avif'];
            if (!isset($allowed[$mime]) || !$image || !isset($image['mime']) || $image['mime'] !== $mime) { @unlink($tmp); throw new RuntimeException('ไฟล์ภาพในแพ็กเกจมีชนิดไม่ถูกต้อง'); }
            $expectedHash = strtolower((string)($asset['sha256'] ?? ''));
            $actualHash = hash_file('sha256', $tmp);
            if ($expectedHash !== '' && preg_match('/^[a-f0-9]{64}$/', $expectedHash) && !hash_equals($expectedHash, $actualHash)) { @unlink($tmp); throw new RuntimeException('ตรวจสอบ SHA-256 ของภาพ SEO ไม่ผ่าน'); }
            $staged[] = ['setting_key'=>(string)$asset['setting_key'],'source_path'=>(string)($asset['source_path'] ?? ''),'package_path'=>$entry,'stage_file'=>basename($tmp),'extension'=>$allowed[$mime],'mime'=>$mime,'sha256'=>$actualHash];
        }
        $zip->close();
        $normalized['staged_assets'] = $staged;
        $normalized['asset_stage_token'] = $staged ? $token : '';
        if (!$staged) { @rmdir($stageDir); }
        return $normalized;
    } catch (Throwable $error) {
        $zip->close();
        foreach (glob($stageDir . DIRECTORY_SEPARATOR . '*') ?: [] as $file) @unlink($file);
        @rmdir($stageDir);
        throw $error;
    }
}
function avsfTransferInstallStagedSeoAssets($preview, &$updates, &$createdFiles) {
    $assets = is_array($preview['staged_assets'] ?? null) ? $preview['staged_assets'] : [];
    $token = (string)($preview['asset_stage_token'] ?? '');
    if (!$assets || !preg_match('/^[a-f0-9]{24}$/', $token) || !isset($updates['seo_social_image'])) return 0;
    $stageRoot = avsfTransferAssetStageRoot();
    $stageDir = realpath($stageRoot . DIRECTORY_SEPARATOR . $token);
    if ($stageDir === false || strpos($stageDir, $stageRoot . DIRECTORY_SEPARATOR) !== 0) throw new RuntimeException('ไม่พบไฟล์ภาพ Preview หรือหมดอายุแล้ว');
    $uploadDir = AVSF_UPLOAD_DIR;
    if (!is_dir($uploadDir) && !@mkdir($uploadDir, 0755, true) && !is_dir($uploadDir)) throw new RuntimeException('สร้างโฟลเดอร์ uploads ไม่สำเร็จ');
    $uploadReal = realpath($uploadDir);
    if ($uploadReal === false || !is_writable($uploadReal) || is_link($uploadDir)) throw new RuntimeException('โฟลเดอร์ uploads ไม่ปลอดภัยหรือเขียนไม่ได้');
    $installed = 0;
    foreach ($assets as $asset) {
        if (!is_array($asset) || ($asset['setting_key'] ?? '') !== 'seo_social_image') continue;
        $stageFile = (string)($asset['stage_file'] ?? '');
        if (!preg_match('/^[a-f0-9]{24}\.img$/', $stageFile)) continue;
        $source = $stageDir . DIRECTORY_SEPARATOR . $stageFile;
        $realSource = realpath($source);
        if ($realSource === false || strpos($realSource, $stageDir . DIRECTORY_SEPARATOR) !== 0 || !is_file($realSource)) throw new RuntimeException('ไม่พบไฟล์ภาพ SEO ที่พักไว้');
        if (!hash_equals((string)$asset['sha256'], hash_file('sha256', $realSource))) throw new RuntimeException('ไฟล์ภาพ SEO เปลี่ยนแปลงหลัง Preview');
        $ext = (string)($asset['extension'] ?? '');
        if (!in_array($ext, ['jpg','png','gif','webp','avif'], true)) throw new RuntimeException('นามสกุลไฟล์ภาพ SEO ไม่ได้รับอนุญาต');
        $filename = bin2hex(random_bytes(16)) . '.' . $ext;
        $destination = $uploadReal . DIRECTORY_SEPARATOR . $filename;
        if (!@copy($realSource, $destination)) throw new RuntimeException('คัดลอกภาพ SEO ไปยังเว็บไซต์ปลายทางไม่สำเร็จ');
        @chmod($destination, 0644);
        $createdFiles[] = $destination;
        $basePath = function_exists('avsfCanonicalBasePath') ? avsfCanonicalBasePath() : '';
        $updates['seo_social_image'] = rtrim($basePath, '/') . '/uploads/' . $filename;
        $installed++;
        break;
    }
    return $installed;
}
